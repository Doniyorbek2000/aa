export function resolveLocaleCode(raw?: string | null): LocaleCode {
  if (!raw) return 'en';
  const clean = raw.trim().toLowerCase().split(/[-_]/)[0] ?? 'en';
  const match = SUPPORTED_LOCALES.find((l) => l.code === clean);
  return match ? match.code : 'en';
}

interface I18nContextValue {
  locale: LocaleCode;
  setLocale: (next: LocaleCode) => void;
  t: TranslationDictionary;
  dir: 'ltr' | 'rtl';
}

const I18nContext = createContext<I18nContextValue>({
  locale: 'en',
  setLocale: () => {},
  t: TRANSLATIONS.en,
  dir: 'ltr',
});

export function I18nProvider({
  children,
  initialLocale,
}: {
  children: React.ReactNode;
  initialLocale?: string;
}) {
  const [locale, setLocaleState] = useState<LocaleCode>(() =>
    initialLocale ? resolveLocaleCode(initialLocale) : 'en'
  );

  useEffect(() => {
    try {
      // 1. Check URL path e.g. /uz, /ru, /de, /ar, /tr, /hi
      const pathSeg = window.location.pathname.split('/').filter(Boolean)[0];
      if (pathSeg && SUPPORTED_LOCALES.some((l) => l.code === pathSeg.toLowerCase())) {
        const matched = resolveLocaleCode(pathSeg);
        setLocaleState(matched);
        window.localStorage.setItem('a12_locale', matched);
        return;
      }

      // 2. Check ?lang= query param
      const qLang = new URLSearchParams(window.location.search).get('lang');
      if (qLang && SUPPORTED_LOCALES.some((l) => l.code === qLang.toLowerCase())) {
        const matched = resolveLocaleCode(qLang);
        setLocaleState(matched);
        window.localStorage.setItem('a12_locale', matched);
        return;
      }

      // 3. Check saved localStorage preference
      const saved = window.localStorage.getItem('a12_locale');
      if (saved && SUPPORTED_LOCALES.some((l) => l.code === saved)) {
        setLocaleState(resolveLocaleCode(saved));
        return;
      }

      // 4. Detect browser language
      if (navigator.language) {
        const detected = resolveLocaleCode(navigator.language);
        setLocaleState(detected);
      }
    } catch {
      // ignore
    }
  }, [initialLocale]);

  const meta = SUPPORTED_LOCALES.find((l) => l.code === locale) ?? DEFAULT_LOCALE_META;
  const dir = meta.dir ?? 'ltr';

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale;
      document.documentElement.dir = dir;
    }
  }, [locale, dir]);

  const setLocale = (next: LocaleCode) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem('a12_locale', next);
      // If user is currently on a locale path like /uz or /ru, update URL cleanly to the new locale
      const parts = window.location.pathname.split('/').filter(Boolean);
      if (parts.length === 1 && SUPPORTED_LOCALES.some((l) => l.code === parts[0])) {
        window.history.replaceState(null, '', `/${next}${window.location.search}${window.location.hash}`);
      }
    } catch {
      // ignore
    }
  };

  return (
    <I18nContext.Provider
      value={{
        locale,
        setLocale,
        t: TRANSLATIONS[locale] ?? TRANSLATIONS.en,
        dir,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

